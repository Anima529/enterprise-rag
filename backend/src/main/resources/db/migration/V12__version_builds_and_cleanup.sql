CREATE FUNCTION fill_version_name() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.name IS NULL THEN
        EXECUTE format('SELECT name FROM %I.document WHERE id=$1',TG_TABLE_SCHEMA) INTO NEW.name USING NEW.document_id;
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER document_version_name BEFORE INSERT ON document_version FOR EACH ROW EXECUTE FUNCTION fill_version_name();

-- Version changes are allowed only to a fully built, strictly newer version.
CREATE OR REPLACE FUNCTION enforce_document_state_transition() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE built boolean;
BEGIN
    IF TG_TABLE_NAME = 'document' AND NEW.current_version <> OLD.current_version THEN
        EXECUTE format('SELECT EXISTS(SELECT 1 FROM %I.document_version WHERE document_id=$1 AND version_no=$2 AND status=''COMPLETED'')',TG_TABLE_SCHEMA)
            INTO built USING NEW.id,NEW.current_version;
        IF NEW.current_version > OLD.current_version AND NEW.status = 'COMPLETED' AND built THEN RETURN NEW; END IF;
        RAISE EXCEPTION 'version must advance to completed index' USING ERRCODE='23514';
    END IF;
    IF OLD.status = NEW.status OR
       (NEW.status='FAILED' AND OLD.status<>'COMPLETED') OR
       (OLD.status='UPLOADED' AND NEW.status='PARSING') OR
       (OLD.status='PARSING' AND NEW.status='CHUNKING') OR
       (OLD.status='CHUNKING' AND NEW.status='EMBEDDING') OR
       (OLD.status='EMBEDDING' AND NEW.status='INDEXING') OR
       (OLD.status='INDEXING' AND NEW.status='COMPLETED') OR
       (OLD.status='FAILED' AND NEW.status IN ('UPLOADED','PARSING')) THEN RETURN NEW; END IF;
    RAISE EXCEPTION 'illegal document state transition: % -> %',OLD.status,NEW.status USING ERRCODE='23514';
END $$;
DROP TRIGGER document_state ON document;
CREATE TRIGGER document_state BEFORE UPDATE OF status,current_version ON document
    FOR EACH ROW EXECUTE FUNCTION enforce_document_state_transition();

CREATE TABLE document_cleanup_task (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    document_id bigint NOT NULL REFERENCES document(id),
    document_version integer NOT NULL,
    cleanup_type varchar(16) NOT NULL CHECK (cleanup_type IN ('OLD_INDEX','DELETED')),
    status varchar(16) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','RUNNING','FAILED','COMPLETED')),
    attempt_count integer NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL,
    error_code varchar(100),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(document_id,document_version,cleanup_type)
);
CREATE INDEX idx_document_cleanup_task_due ON document_cleanup_task(next_attempt_at,id) WHERE status<>'COMPLETED';
CREATE TRIGGER document_cleanup_task_updated BEFORE UPDATE ON document_cleanup_task
    FOR EACH ROW EXECUTE FUNCTION update_business_timestamp();
COMMENT ON TABLE document_cleanup_task IS '旧版索引及已删除文档清理任务，失败持久重试；旧版本原件保留供引用';
COMMENT ON COLUMN document_cleanup_task.document_version IS '清理的版本号，0 表示已删除文档的全部版本';
COMMENT ON COLUMN document_cleanup_task.next_attempt_at IS '延迟清理时间或执行租约到期时间';
