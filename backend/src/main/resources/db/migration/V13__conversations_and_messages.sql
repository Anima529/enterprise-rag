CREATE TABLE conversation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    user_id bigint NOT NULL REFERENCES sys_user(id),
    title varchar(100) NOT NULL CHECK (length(btrim(title))>0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted boolean NOT NULL DEFAULT false,
    UNIQUE(id,user_id)
);
CREATE INDEX idx_conversation_owner ON conversation(user_id,updated_at DESC,id DESC) WHERE NOT deleted;
CREATE TRIGGER conversation_updated BEFORE UPDATE ON conversation FOR EACH ROW EXECUTE FUNCTION update_business_timestamp();
CREATE TABLE chat_message (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    conversation_id bigint NOT NULL,
    user_id bigint NOT NULL,
    role varchar(16) NOT NULL CHECK (role IN ('USER','ASSISTANT')),
    content text NOT NULL DEFAULT '',
    request_id varchar(36) NOT NULL,
    trace_id varchar(36) NOT NULL,
    status varchar(16) NOT NULL CHECK (status IN ('GENERATING','COMPLETED','FAILED','CANCELLED')),
    error_code varchar(100),
    knowledge_base_ids jsonb NOT NULL,
    retrieval_mode varchar(16) NOT NULL DEFAULT 'VECTOR',
    confidence_level varchar(16) NOT NULL DEFAULT 'LOW',
    faithfulness_status varchar(32) NOT NULL DEFAULT 'UNKNOWN',
    input_tokens bigint,
    output_tokens bigint,
    expires_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY(conversation_id,user_id) REFERENCES conversation(id,user_id) ON DELETE CASCADE,
    UNIQUE(request_id,role)
);
CREATE UNIQUE INDEX uk_chat_active ON chat_message(conversation_id) WHERE role='ASSISTANT' AND status='GENERATING';
CREATE INDEX idx_message_history ON chat_message(conversation_id,id);
CREATE TRIGGER chat_message_updated BEFORE UPDATE ON chat_message FOR EACH ROW EXECUTE FUNCTION update_business_timestamp();
CREATE TABLE message_citation (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    message_id bigint NOT NULL REFERENCES chat_message(id) ON DELETE CASCADE,
    citation_id varchar(16) NOT NULL,
    chunk_id bigint NOT NULL,
    document_id bigint NOT NULL,
    document_version integer NOT NULL,
    document_name varchar(255) NOT NULL,
    page_number integer,
    chapter text,
    section text,
    line_start integer,
    line_end integer,
    snippet text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(message_id,citation_id)
);
-- Snapshot IDs deliberately have no Chunk FK: delayed index cleanup cannot invalidate historical evidence.
COMMENT ON TABLE conversation IS '用户拥有的问答会话，软删除';
COMMENT ON TABLE chat_message IS '问答消息与生成终态；不保存模型私有思维链';
COMMENT ON COLUMN chat_message.expires_at IS '生成请求总超时，重启或断流后由历史读取回收';
COMMENT ON TABLE message_citation IS '本次入模证据的版本和正文快照，原文下载仍需实时鉴权';
