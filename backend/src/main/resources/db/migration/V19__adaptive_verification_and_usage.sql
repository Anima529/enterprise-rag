CREATE TABLE ai_price (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model varchar(120) NOT NULL,
    version varchar(80) NOT NULL,
    currency varchar(3) NOT NULL CHECK(currency IN ('CNY')),
    basis varchar(24) NOT NULL CHECK(basis IN ('TOKENS','CALL','UNITS')),
    input_price numeric(20,8) NOT NULL CHECK(input_price>=0),
    output_price numeric(20,8) NOT NULL CHECK(output_price>=0),
    effective_at timestamptz NOT NULL DEFAULT now(),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(model,version)
);
CREATE TABLE ai_usage (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id varchar(120) NOT NULL,
    trace_id varchar(120) NOT NULL,
    call_id varchar(36) NOT NULL,
    user_id bigint REFERENCES sys_user(id),
    department_id bigint REFERENCES sys_department(id),
    conversation_id bigint REFERENCES conversation(id) ON DELETE SET NULL,
    message_id bigint REFERENCES chat_message(id) ON DELETE SET NULL,
    stage varchar(24) NOT NULL CHECK(stage IN ('REWRITE','ROUTE','DECOMPOSE','HYDE','EMBEDDING','RERANK','GENERATION','FAITHFULNESS')),
    provider varchar(40) NOT NULL,
    model varchar(120) NOT NULL,
    input_tokens bigint CHECK(input_tokens>=0),
    output_tokens bigint CHECK(output_tokens>=0),
    units bigint CHECK(units>=0),
    calls integer NOT NULL DEFAULT 1 CHECK(calls=1),
    latency_ms bigint NOT NULL CHECK(latency_ms>=0),
    success boolean NOT NULL,
    error_code varchar(100),
    price_id bigint REFERENCES ai_price(id),
    price_version varchar(80),
    currency varchar(3) NOT NULL DEFAULT 'CNY',
    estimated_cost numeric(24,10) CHECK(estimated_cost>=0),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(request_id,stage,call_id)
);
CREATE INDEX idx_ai_usage_user_time ON ai_usage(user_id,created_at,id);
CREATE INDEX idx_ai_usage_time_stage ON ai_usage(created_at,stage);
CREATE TABLE rag_request_trace (
    request_id varchar(120) PRIMARY KEY,
    trace_id varchar(120) NOT NULL,
    user_id bigint NOT NULL REFERENCES sys_user(id),
    department_id bigint NOT NULL REFERENCES sys_department(id),
    message_id bigint REFERENCES chat_message(id) ON DELETE SET NULL,
    route varchar(16) NOT NULL DEFAULT 'STANDARD',
    reason_code varchar(80) NOT NULL DEFAULT 'PENDING',
    status varchar(16) NOT NULL DEFAULT 'RUNNING',
    latency_ms bigint NOT NULL DEFAULT 0,
    first_token_ms bigint,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_rag_trace_user_time ON rag_request_trace(user_id,created_at);
