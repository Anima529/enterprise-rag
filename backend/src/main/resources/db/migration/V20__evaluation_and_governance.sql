CREATE TABLE evaluation_dataset (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    name varchar(160) NOT NULL,
    description text NOT NULL DEFAULT '',
    evaluation_user_id bigint NOT NULL REFERENCES sys_user(id),
    created_by bigint NOT NULL REFERENCES sys_user(id),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    deleted boolean NOT NULL DEFAULT false
);
CREATE TABLE evaluation_case (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    dataset_id bigint NOT NULL REFERENCES evaluation_dataset(id) ON DELETE CASCADE,
    case_index integer NOT NULL CHECK (case_index >= 0),
    case_snapshot jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE(dataset_id, case_index)
);
CREATE TABLE evaluation_run (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    dataset_id bigint NOT NULL REFERENCES evaluation_dataset(id),
    name varchar(160) NOT NULL,
    mode varchar(40) NOT NULL CHECK (mode IN ('VECTOR', 'HYBRID', 'HYBRID_RERANK')),
    status varchar(20) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'RUNNING', 'COMPLETED', 'FAILED')),
    config_snapshot jsonb NOT NULL,
    summary jsonb,
    error_code varchar(80),
    lease_owner varchar(80),
    lease_expires_at timestamptz,
    started_at timestamptz,
    finished_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX evaluation_run_queue_idx ON evaluation_run(status, id);
CREATE TABLE evaluation_result (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    run_id bigint NOT NULL REFERENCES evaluation_run(id) ON DELETE CASCADE,
    case_id bigint NOT NULL REFERENCES evaluation_case(id),
    result_snapshot jsonb NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE(run_id, case_id)
);
CREATE TABLE audit_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint REFERENCES sys_user(id) ON DELETE SET NULL,
    action varchar(80) NOT NULL,
    resource_id bigint,
    request_id varchar(80),
    trace_id varchar(80),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX audit_log_created_idx ON audit_log(created_at, id);
ALTER TABLE rag_request_trace ADD COLUMN cache_hit boolean NOT NULL DEFAULT false;
COMMENT ON TABLE evaluation_dataset IS '不可变离线评估数据集，固定执行身份';
COMMENT ON TABLE evaluation_case IS '评估问题、历史、相关 Child 集合及权限预期快照';
COMMENT ON TABLE evaluation_run IS '持久异步实验与配置快照，租约失效后明确失败';
COMMENT ON TABLE evaluation_result IS '每题排序、回答、核验、指标和错误追踪快照';
COMMENT ON TABLE audit_log IS '敏感操作审计，不保存凭证、模型密钥或请求正文';
COMMENT ON COLUMN rag_request_trace.cache_hit IS '已通过当前权限和版本复查的答案缓存命中';
