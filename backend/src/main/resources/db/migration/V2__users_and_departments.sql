CREATE TABLE sys_department (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    code varchar(32) NOT NULL UNIQUE CHECK (code ~ '^[A-Z][A-Z0-9_]{1,31}$'),
    name varchar(100) NOT NULL CHECK (length(trim(name)) > 0),
    status varchar(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DISABLED')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted boolean NOT NULL DEFAULT false
);

CREATE TABLE sys_user (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    username varchar(64) NOT NULL UNIQUE CHECK (username ~ '^[a-z][a-z0-9_.-]{2,63}$'),
    password_hash varchar(60) NOT NULL CHECK (password_hash ~ '^\$2[aby]\$(1[0-6])\$[./A-Za-z0-9]{53}$'),
    department_id bigint NOT NULL REFERENCES sys_department(id),
    role varchar(32) NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'SYSTEM_ADMIN')),
    status varchar(16) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DISABLED')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted boolean NOT NULL DEFAULT false
);
CREATE INDEX idx_sys_user_department ON sys_user(department_id);

CREATE FUNCTION update_business_timestamp() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$;
CREATE TRIGGER sys_department_updated BEFORE UPDATE ON sys_department
    FOR EACH ROW EXECUTE FUNCTION update_business_timestamp();
CREATE TRIGGER sys_user_updated BEFORE UPDATE ON sys_user
    FOR EACH ROW EXECUTE FUNCTION update_business_timestamp();
