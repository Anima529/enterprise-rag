CREATE TABLE knowledge_base (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    name varchar(100) NOT NULL CHECK (length(trim(name)) > 0),
    description varchar(2000) NOT NULL DEFAULT '',
    department_id bigint NOT NULL REFERENCES sys_department(id),
    owner_user_id bigint NOT NULL REFERENCES sys_user(id),
    visibility varchar(16) NOT NULL DEFAULT 'PRIVATE' CHECK (visibility = 'PRIVATE'),
    status varchar(16) NOT NULL DEFAULT 'ENABLED' CHECK (status IN ('ENABLED', 'DISABLED')),
    embedding_model varchar(100) NOT NULL DEFAULT 'text-embedding-v3',
    embedding_dimensions integer NOT NULL DEFAULT 1024 CHECK (embedding_dimensions = 1024),
    generation_model varchar(100) NOT NULL DEFAULT 'qwen-plus',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted boolean NOT NULL DEFAULT false
);
CREATE INDEX idx_kb_department ON knowledge_base(department_id, id) WHERE deleted = false;
CREATE INDEX idx_kb_owner ON knowledge_base(owner_user_id, id) WHERE deleted = false;
CREATE TRIGGER knowledge_base_updated BEFORE UPDATE ON knowledge_base
    FOR EACH ROW EXECUTE FUNCTION update_business_timestamp();

CREATE TABLE knowledge_base_acl (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    knowledge_base_id bigint NOT NULL REFERENCES knowledge_base(id),
    subject_type varchar(16) NOT NULL CHECK (subject_type IN ('USER', 'DEPARTMENT', 'ROLE')),
    subject_id varchar(32) NOT NULL,
    permission varchar(16) NOT NULL CHECK (permission IN ('READ', 'WRITE', 'ADMIN')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (knowledge_base_id, subject_type, subject_id),
    CHECK (CASE WHEN subject_type = 'ROLE' THEN subject_id IN ('USER', 'SYSTEM_ADMIN')
        WHEN subject_id ~ '^[1-9][0-9]{0,15}$' THEN subject_id::numeric <= 9007199254740991
        ELSE false END)
);
CREATE INDEX idx_kb_acl_subject ON knowledge_base_acl(subject_type, subject_id, knowledge_base_id);
CREATE TRIGGER knowledge_base_acl_updated BEFORE UPDATE ON knowledge_base_acl
    FOR EACH ROW EXECUTE FUNCTION update_business_timestamp();
