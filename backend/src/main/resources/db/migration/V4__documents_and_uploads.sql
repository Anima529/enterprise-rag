CREATE TABLE document (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    knowledge_base_id bigint NOT NULL REFERENCES knowledge_base(id),
    current_version integer NOT NULL DEFAULT 1 CHECK (current_version > 0),
    name varchar(255) NOT NULL CHECK (length(trim(name)) > 0),
    source_format varchar(8) NOT NULL CHECK (source_format IN ('PDF','DOCX','XLSX','TXT','MD')),
    mime_type varchar(128) NOT NULL,
    size_bytes bigint NOT NULL CHECK (size_bytes > 0),
    sha256 char(64) NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    object_key varchar(255) NOT NULL UNIQUE,
    status varchar(16) NOT NULL DEFAULT 'UPLOADED'
        CHECK (status IN ('UPLOADED','PARSING','CHUNKING','EMBEDDING','INDEXING','COMPLETED','FAILED')),
    created_by bigint NOT NULL REFERENCES sys_user(id),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    deleted boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX uk_document_active_sha ON document(knowledge_base_id, sha256) WHERE deleted = false;
CREATE INDEX idx_document_kb ON document(knowledge_base_id, id) WHERE deleted = false;
CREATE TRIGGER document_updated BEFORE UPDATE ON document
    FOR EACH ROW EXECUTE FUNCTION update_business_timestamp();

CREATE TABLE document_version (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    document_id bigint NOT NULL REFERENCES document(id),
    version_no integer NOT NULL CHECK (version_no > 0),
    source_format varchar(8) NOT NULL CHECK (source_format IN ('PDF','DOCX','XLSX','TXT','MD')),
    mime_type varchar(128) NOT NULL,
    size_bytes bigint NOT NULL CHECK (size_bytes > 0),
    sha256 char(64) NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    object_key varchar(255) NOT NULL,
    status varchar(16) NOT NULL DEFAULT 'UPLOADED'
        CHECK (status IN ('UPLOADED','PARSING','CHUNKING','EMBEDDING','INDEXING','COMPLETED','FAILED')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(document_id, version_no)
);
ALTER TABLE document ADD CONSTRAINT fk_document_current_version
    FOREIGN KEY (id, current_version) REFERENCES document_version(document_id, version_no)
    DEFERRABLE INITIALLY DEFERRED;
CREATE INDEX idx_document_version_object ON document_version(object_key);
CREATE TRIGGER document_version_updated BEFORE UPDATE ON document_version
    FOR EACH ROW EXECUTE FUNCTION update_business_timestamp();

CREATE TABLE document_index_task (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    document_id bigint NOT NULL,
    document_version integer NOT NULL CHECK (document_version > 0),
    task_type varchar(16) NOT NULL DEFAULT 'INDEX' CHECK (task_type IN ('INDEX','REINDEX')),
    status varchar(16) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','RUNNING','COMPLETED','FAILED')),
    retry_count integer NOT NULL DEFAULT 0 CHECK (retry_count >= 0),
    error_code varchar(100),
    error_message varchar(1000),
    started_at timestamptz,
    finished_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(document_id, document_version, task_type),
    FOREIGN KEY(document_id, document_version) REFERENCES document_version(document_id, version_no)
);
CREATE INDEX idx_document_task_pending ON document_index_task(status, created_at, id);
CREATE TRIGGER document_index_task_updated BEFORE UPDATE ON document_index_task
    FOR EACH ROW EXECUTE FUNCTION update_business_timestamp();

-- Upload intent is durable before MinIO is called. Successful commit removes it atomically.
-- Crashes and failed compensation leave a bounded, retryable orphan cleanup record.
CREATE TABLE document_storage_cleanup (
    object_key varchar(255) PRIMARY KEY,
    next_attempt_at timestamptz NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idx_document_cleanup_due ON document_storage_cleanup(next_attempt_at);
CREATE TRIGGER document_storage_cleanup_updated BEFORE UPDATE ON document_storage_cleanup
    FOR EACH ROW EXECUTE FUNCTION update_business_timestamp();
