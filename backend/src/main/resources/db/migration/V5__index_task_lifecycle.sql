ALTER TABLE document_index_task
    ADD COLUMN stage varchar(16) NOT NULL DEFAULT 'UPLOADED'
        CHECK (stage IN ('UPLOADED','PARSING','CHUNKING','EMBEDDING','INDEXING','COMPLETED','FAILED')),
    ADD COLUMN attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    ADD COLUMN auto_retry_count integer NOT NULL DEFAULT 0 CHECK (auto_retry_count >= 0),
    ADD COLUMN next_attempt_at timestamptz NOT NULL DEFAULT now(),
    ADD COLUMN lease_owner varchar(36),
    ADD COLUMN lease_expires_at timestamptz,
    ADD CONSTRAINT ck_task_running_lease CHECK (
        (status = 'RUNNING' AND lease_owner IS NOT NULL AND lease_expires_at IS NOT NULL)
        OR (status <> 'RUNNING' AND lease_owner IS NULL AND lease_expires_at IS NULL));
CREATE INDEX idx_task_due ON document_index_task(next_attempt_at, id) WHERE status = 'PENDING';
CREATE INDEX idx_task_expired ON document_index_task(lease_expires_at, id) WHERE status = 'RUNNING';

CREATE TABLE document_index_step (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    task_id bigint NOT NULL REFERENCES document_index_task(id) ON DELETE CASCADE,
    attempt integer NOT NULL CHECK (attempt > 0),
    stage varchar(16) NOT NULL CHECK (stage IN ('PARSING','CHUNKING','EMBEDDING','INDEXING')),
    status varchar(16) NOT NULL DEFAULT 'RUNNING' CHECK (status IN ('RUNNING','COMPLETED','FAILED')),
    started_at timestamptz NOT NULL DEFAULT now(),
    finished_at timestamptz,
    error_code varchar(100),
    error_message varchar(1000),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE(task_id, attempt, stage)
);
CREATE TRIGGER document_index_step_updated BEFORE UPDATE ON document_index_step
    FOR EACH ROW EXECUTE FUNCTION update_business_timestamp();

CREATE FUNCTION enforce_document_state_transition() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status = NEW.status OR
       (NEW.status = 'FAILED' AND OLD.status <> 'COMPLETED') OR
       (OLD.status = 'UPLOADED' AND NEW.status = 'PARSING') OR
       (OLD.status = 'PARSING' AND NEW.status = 'CHUNKING') OR
       (OLD.status = 'CHUNKING' AND NEW.status = 'EMBEDDING') OR
       (OLD.status = 'EMBEDDING' AND NEW.status = 'INDEXING') OR
       (OLD.status = 'INDEXING' AND NEW.status = 'COMPLETED') OR
       (OLD.status = 'FAILED' AND NEW.status IN ('UPLOADED','PARSING')) THEN
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'illegal document state transition: % -> %', OLD.status, NEW.status USING ERRCODE = '23514';
END $$;
CREATE TRIGGER document_state BEFORE UPDATE OF status ON document
    FOR EACH ROW EXECUTE FUNCTION enforce_document_state_transition();
CREATE TRIGGER document_version_state BEFORE UPDATE OF status ON document_version
    FOR EACH ROW EXECUTE FUNCTION enforce_document_state_transition();

CREATE FUNCTION enforce_task_state_transition() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF OLD.status = NEW.status OR
       (OLD.status = 'PENDING' AND NEW.status IN ('RUNNING','FAILED')) OR
       (OLD.status = 'RUNNING' AND NEW.status IN ('PENDING','FAILED','COMPLETED')) OR
       (OLD.status = 'FAILED' AND NEW.status = 'PENDING') THEN
        RETURN NEW;
    END IF;
    RAISE EXCEPTION 'illegal task state transition: % -> %', OLD.status, NEW.status USING ERRCODE = '23514';
END $$;
CREATE TRIGGER document_task_state BEFORE UPDATE OF status ON document_index_task
    FOR EACH ROW EXECUTE FUNCTION enforce_task_state_transition();
