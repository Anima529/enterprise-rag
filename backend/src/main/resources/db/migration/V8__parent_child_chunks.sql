ALTER TABLE knowledge_base ADD CONSTRAINT uk_kb_department_pair UNIQUE (id, department_id);
ALTER TABLE document ADD CONSTRAINT uk_document_kb_pair UNIQUE (id, knowledge_base_id);

CREATE TABLE document_chunk_result (
    document_id BIGINT NOT NULL,
    document_version INTEGER NOT NULL,
    strategy_version VARCHAR(64) NOT NULL,
    tokenizer VARCHAR(32) NOT NULL,
    child_tokens INTEGER NOT NULL CHECK (child_tokens > 0),
    parent_tokens INTEGER NOT NULL CHECK (parent_tokens >= child_tokens),
    overlap_tokens INTEGER NOT NULL CHECK (overlap_tokens >= 0 AND overlap_tokens < child_tokens),
    parent_count INTEGER NOT NULL CHECK (parent_count > 0),
    child_count INTEGER NOT NULL CHECK (child_count > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (document_id, document_version),
    FOREIGN KEY (document_id, document_version) REFERENCES document_version(document_id, version_no) ON DELETE CASCADE
);

CREATE TABLE document_chunk (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    knowledge_base_id BIGINT NOT NULL,
    department_id BIGINT NOT NULL,
    document_id BIGINT NOT NULL,
    document_version INTEGER NOT NULL,
    parent_chunk_id BIGINT,
    parent_type VARCHAR(8),
    chunk_type VARCHAR(8) NOT NULL CHECK (chunk_type IN ('PARENT', 'CHILD')),
    chunk_index INTEGER NOT NULL CHECK (chunk_index >= 0),
    content TEXT NOT NULL CHECK (length(btrim(content)) > 0),
    token_count INTEGER NOT NULL CHECK (token_count > 0),
    page_number INTEGER CHECK (page_number > 0),
    chapter TEXT,
    section TEXT,
    metadata JSONB NOT NULL CHECK (jsonb_typeof(metadata) = 'object'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted BOOLEAN NOT NULL DEFAULT false,
    UNIQUE (document_id, document_version, chunk_type, chunk_index),
    UNIQUE (id, document_id, document_version, knowledge_base_id, department_id, chunk_type),
    CHECK ((chunk_type = 'PARENT' AND parent_chunk_id IS NULL AND parent_type IS NULL)
        OR (chunk_type = 'CHILD' AND parent_chunk_id IS NOT NULL AND parent_type IS NOT NULL AND parent_type = 'PARENT')),
    FOREIGN KEY (knowledge_base_id, department_id) REFERENCES knowledge_base(id, department_id),
    FOREIGN KEY (document_id, knowledge_base_id) REFERENCES document(id, knowledge_base_id) ON DELETE CASCADE,
    FOREIGN KEY (document_id, document_version) REFERENCES document_chunk_result(document_id, document_version) ON DELETE CASCADE,
    FOREIGN KEY (parent_chunk_id, document_id, document_version, knowledge_base_id, department_id, parent_type)
        REFERENCES document_chunk(id, document_id, document_version, knowledge_base_id, department_id, chunk_type)
        DEFERRABLE INITIALLY DEFERRED
);
CREATE INDEX idx_chunk_preview ON document_chunk(document_id, document_version, chunk_index) WHERE deleted = false;
CREATE INDEX idx_chunk_parent ON document_chunk(parent_chunk_id) WHERE deleted = false;
CREATE INDEX idx_chunk_scope ON document_chunk(knowledge_base_id, department_id, document_id, document_version) WHERE deleted = false;
CREATE TRIGGER document_chunk_updated BEFORE UPDATE ON document_chunk
    FOR EACH ROW EXECUTE FUNCTION update_business_timestamp();
CREATE TRIGGER document_chunk_result_updated BEFORE UPDATE ON document_chunk_result
    FOR EACH ROW EXECUTE FUNCTION update_business_timestamp();
